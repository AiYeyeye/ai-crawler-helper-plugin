export const dict = { zh, en } as const;

export type DictKey = keyof typeof zh;

/** Single-key lookup. Throws at runtime only if a key was missed in `en` (compile-time enforced anyway). */
export const t = (locale: Locale, key: DictKey): string => dict[locale][key];

/** Lookup with `{name}` placeholder substitution. */
export const tpl = (
  locale: Locale,
  key: DictKey,
  params: Readonly<Record<string, string | number>>,
): string => {
  let out = t(locale, key);
  for (const [name, value] of Object.entries(params)) {
    out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
};
